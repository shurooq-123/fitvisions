import 'dart:ui' as ui;
import 'package:flutter/services.dart';

class DressReference {
  const DressReference(
      this.id,
      this.sheet,
      this.position,
      this.colour,
      this.length,
      this.cut,
      this.neckline,
      this.sleeves,
      this.fabric,
      this.style,
      this.bounds);
  final String id,
      sheet,
      position,
      colour,
      length,
      cut,
      neckline,
      sleeves,
      fabric,
      style;
  final List<double> bounds;
  String get asset => 'images/dress_reference_$sheet.png';
  String get gender => 'Female';
  String get type => 'Dress';
  String get fashionStyle => length == 'Short'
      ? 'Party'
      : fabric == 'Lace'
          ? 'Soft'
          : 'Evening';
  List<String> get occasions => sheet == 'white'
      ? ['Bridal dress', 'Wedding guest', 'Birthday']
      : ['Wedding guest', 'Birthday', 'Other'];
  String get description =>
      '$id: $colour $length $cut dress; $neckline neckline; $sleeves; $style. Fabric appearance: $fabric (estimated from image).';
  int score(Map<String, String> answers) {
    int score = 0;
    for (final pair in <String, String>{
      'Favourite colour': colour,
      'Length': length,
      'Silhouette': cut,
      'Neckline': neckline,
      'Sleeves': sleeves,
      'Fabric': fabric,
      'Style': fashionStyle
    }.entries) {
      if (answers[pair.key] == pair.value) {
        score += pair.key == 'Silhouette' ? 4 : 3;
      }
    }
    if (occasions.contains(answers['Occasion'])) score++;
    if (answers['Fit'] == 'Fitted' &&
        ['Bodycon', 'Mermaid', 'Sheath'].contains(cut)) {
      score += 2;
    }
    if (answers['Fit'] == 'Loose' && cut == 'A-line') score += 2;
    return score;
  }

  // Crop only the chosen garment at runtime, keeping the original collage intact.
  Future<Uint8List> imageBytes() async {
    final data = await rootBundle.load(asset);
    final codec = await ui.instantiateImageCodec(data.buffer.asUint8List());
    final frame = await codec.getNextFrame();
    final image = frame.image;
    final rect = ui.Rect.fromLTRB(
        bounds[0] * image.width,
        bounds[1] * image.height,
        bounds[2] * image.width,
        bounds[3] * image.height);
    final recorder = ui.PictureRecorder();
    ui.Canvas(recorder).drawImageRect(image, rect,
        ui.Rect.fromLTWH(0, 0, rect.width, rect.height), ui.Paint());
    final picture = recorder.endRecording();
    final cropped =
        await picture.toImage(rect.width.ceil(), rect.height.ceil());
    final png = await cropped.toByteData(format: ui.ImageByteFormat.png);
    cropped.dispose();
    picture.dispose();
    image.dispose();
    codec.dispose();
    if (png == null) {
      throw StateError('Could not load the selected dress reference');
    }
    return png.buffer.asUint8List();
  }
}

List<DressReference> rankedDressReferences(Map<String, String> answers) {
  if (answers['Gender / clothing style'] != 'Female' ||
      (answers['Age group'] ?? '').startsWith('Child') ||
      (answers['Age group'] ?? '').startsWith('Teen') ||
      answers['Occasion'] == 'Abaya') {
    return [];
  }
  final results = dressReferences.toList();
  results.sort((a, b) {
    final score = b.score(answers).compareTo(a.score(answers));
    return score != 0 ? score : a.id.compareTo(b.id);
  });
  return results;
}

